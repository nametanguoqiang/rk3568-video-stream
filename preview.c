// 只有这一处定义 STB_IMAGE_IMPLEMENTATION，多一处就重复定义
#define STB_IMAGE_IMPLEMENTATION
#include "stb_image.h"

static int g_fb = -1;                   // /dev/fb0 的描述符
static unsigned char *g_fbmem = NULL;   // 映射出来的显存
static size_t g_fblen = 0;              // 映射长度
static struct fb_var_screeninfo g_var;  // 分辨率、位深、RGB 位域
static struct fb_fix_screeninfo g_fix;  // 行字节数

int preview_init(const char *fbdev)
{
	g_fb = open(fbdev, O_RDWR);
	if (g_fb < 0)
	{
		perror("open fb");
		return -1;
	}

	if (ioctl(g_fb, FBIOGET_VSCREENINFO, &g_var) < 0)
	{
		perror("FBIOGET_VSCREENINFO");
		close(g_fb);
		g_fb = -1;
		return -1;
	}

	if (ioctl(g_fb, FBIOGET_FSCREENINFO, &g_fix) < 0)
	{
		perror("FBIOGET_FSCREENINFO");
		close(g_fb);
		g_fb = -1;
		return -1;
	}

	// 映射长度按 stride 乘行数算，不能用 宽 x 高 x 4，驱动有对齐补齐
	g_fblen = (size_t)g_fix.line_length * g_var.yres;
	g_fbmem = mmap(NULL, g_fblen, PROT_READ | PROT_WRITE, MAP_SHARED, g_fb, 0);
	if (g_fbmem == MAP_FAILED)
	{
		perror("mmap fb");
		g_fbmem = NULL;
		close(g_fb);
		g_fb = -1;
		return -1;
	}

	memset(g_fbmem, 0, g_fblen);        // 先整屏清黑，居中留出的边不残留乱码

	printf("[PREV] 屏幕 %ux%u, %u bpp, 行字节 %u\n",
		   g_var.xres, g_var.yres, g_var.bits_per_pixel, g_fix.line_length);
	return 0;
}

// 按 var_screeninfo 里的位域拼像素，不硬写 RGB 的顺序
static unsigned int make_pixel(unsigned char r, unsigned char g, unsigned char b)
{
	unsigned int px = 0;

	px |= ((unsigned int)(r >> (8 - g_var.red.length))   << g_var.red.offset);
	px |= ((unsigned int)(g >> (8 - g_var.green.length)) << g_var.green.offset);
	px |= ((unsigned int)(b >> (8 - g_var.blue.length))  << g_var.blue.offset);

	// 有些驱动的 32 位格式认 alpha，填满才不透明，不填就是全黑
	if (g_var.transp.length > 0)
		px |= ((1u << g_var.transp.length) - 1u) << g_var.transp.offset;

	return px;
}

