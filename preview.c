// 在 SOI 后面插入四张标准表，返回拼好的帧，超长或数据异常返回 NULL
static unsigned char *jpeg_with_dht(const struct frame *f, size_t *outlen)
{
	if (f->len < 4 || f->len - 2 + 2 + sizeof(g_dht) > sizeof(g_jpg))
		return NULL;

	memcpy(g_jpg, f->data, 2);                      // SOI 原样保留
	memcpy(g_jpg + 2, g_dht, sizeof(g_dht));        // 补 DC/AC 四张表
	memcpy(g_jpg + 2 + sizeof(g_dht), f->data + 2, f->len - 2);

	*outlen = 2 + sizeof(g_dht) + f->len - 2;
	return g_jpg;
}

// 把一张 RGB 图等比缩进屏幕，居中显示
static void draw_rgb(const unsigned char *rgb, int w, int h)
{
	unsigned int sw = g_var.xres;
	unsigned int sh = g_var.yres;
	unsigned int dw = sw;
	unsigned int dh = (unsigned int)h * sw / (unsigned int)w;

	// 按宽度铺满算出来的高度超过屏幕，就改成按高度铺满
	if (dh > sh)
	{
		dh = sh;
		dw = (unsigned int)w * sh / (unsigned int)h;
	}

	unsigned int ox = (sw - dw) / 2;    // 水平居中，剩下的当黑边
	unsigned int oy = (sh - dh) / 2;
	unsigned int bpp = g_var.bits_per_pixel / 8;

	for (unsigned int y = 0; y < dh; y++)
	{
		// 最近邻采样：目标行反算源图行，不做插值，快
		unsigned int sy = (unsigned int)y * (unsigned int)h / dh;
		unsigned char *dst = g_fbmem + (size_t)(oy + y) * g_fix.line_length
				   + (size_t)ox * bpp;
		const unsigned char *src = rgb + (size_t)sy * (size_t)w * 3;

		for (unsigned int x = 0; x < dw; x++)
		{
			unsigned int sx = (unsigned int)x * (unsigned int)w / dw;
			const unsigned char *p = src + (size_t)sx * 3;
			unsigned int px = make_pixel(p[0], p[1], p[2]);

			if (g_var.bits_per_pixel == 16)
			{
				*(unsigned short *)dst = (unsigned short)px;
				dst += 2;
			}
			else
			{
				*(unsigned int *)dst = px;
				dst += 4;
			}
		}
	}
}

void *preview_thread(void *arg)
{
	struct preview_ctx *ctx = arg;
	struct frame f;
	unsigned long n = 0;

	while (ring_get(ctx->ring, &f, ctx->stop) == 0)
	{
		int w = 0;
		int h = 0;
		int ch = 0;

		// 从内存里解 jpg，最后一个参数 3 表示只要 RGB 三通道，丢掉 alpha
		size_t jlen = 0;
		unsigned char *jpg = jpeg_with_dht(&f, &jlen);
		unsigned char *rgb = NULL;

		if (jpg != NULL)
			rgb = stbi_load_from_memory(jpg, (int)jlen, &w, &h, &ch, 3);

		if (rgb != NULL)
		{
			draw_rgb(rgb, w, h);
			stbi_image_free(rgb);
		}
		ring_free(&f);

		if (++n % 15 == 0)              // 每 15 帧打一次，兼当心跳
			printf("[PREV] 已显示 %lu 帧\n", n);
	}

	printf("\n预览线程退出，共显示 %lu 帧\n", n);
	return NULL;
}

void preview_deinit(void)
{
	if (g_fbmem != NULL)
	{
		munmap(g_fbmem, g_fblen);
		g_fbmem = NULL;
	}
	if (g_fb >= 0)
	{
		close(g_fb);
		g_fb = -1;
	}
}